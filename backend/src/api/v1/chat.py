"""
Chat API — Pre-Retrieval ACL Filtered Streaming RAG.
POST /api/v1/chat/stream
Streams tokens using Server-Sent Events (SSE).
"""
from __future__ import annotations

from typing import Optional

from fastapi import APIRouter, Depends, Request
from fastapi.responses import StreamingResponse
from pydantic import BaseModel, Field
from sqlalchemy.ext.asyncio import AsyncSession

from src.api.v1.auth import get_current_user
from src.api.v1.permissions import get_auth_service
from src.infrastructure.database.connection import get_db_session
from src.infrastructure.database.models import User
from src.infrastructure.embeddings.local_embedder import LocalEmbedder
from src.infrastructure.llm.ollama_adapter import get_llm_provider
from src.infrastructure.vector_store.pgvector_store import PgVectorStore
from src.services.authorization_service import AuthorizationService
from src.services.chat_service import ChatService
from src.services.retrieval_service import RetrievalService

router = APIRouter(prefix="/chat", tags=["Chat"])
embedder_singleton = LocalEmbedder()


class ChatRequest(BaseModel):
    question: str = Field(min_length=1, max_length=2000)
    conversation_id: Optional[str] = None


@router.post("/stream")
async def stream_chat(
    request: Request,
    body: ChatRequest,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db_session),
    auth_service: AuthorizationService = Depends(get_auth_service),
) -> StreamingResponse:
    """
    Execute streaming RAG with pre-retrieval authorization.
    Tokens are streamed via SSE as they are generated by the LLM.
    """
    vector_store = PgVectorStore(session=db)
    retrieval_service = RetrievalService(
        authorization_service=auth_service,
        embedder=embedder_singleton,
        vector_store=vector_store,
    )
    llm_provider = get_llm_provider()
    chat_service = ChatService(
        retrieval_service=retrieval_service,
        llm_provider=llm_provider,
    )

    # Stream generator
    event_stream = chat_service.stream_response(
        question=body.question,
        user_id=str(current_user.id),
        tenant_id=str(current_user.tenant_id),
        conversation_id=body.conversation_id,
    )

    return StreamingResponse(
        event_stream,
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",
        },
    )

